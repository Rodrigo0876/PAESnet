function updateProgress() {

  const answeredQuestions =
    Object.keys(userAnswers).length;

  const percentage =
    Math.round(
      (
        answeredQuestions /
        questions.length
      ) * 100
    );

  progressText.textContent =
    `${percentage}%`;

  examProgressFill.style.width =
    `${percentage}%`;
}


// =============================================
// FINALIZAR ENSAYO
// =============================================

function finishExam() {

  const unansweredQuestions =
    questions.length -
    Object.keys(userAnswers).length;

  if (unansweredQuestions > 0) {

    const confirmFinish =
      confirm(
        `Todavía tienes ${unansweredQuestions} pregunta(s) sin responder. ¿Deseas finalizar igualmente?`
      );

    if (!confirmFinish) {
      return;
    }
  }

  let correctAnswers = 0;

  questions.forEach(
    (question, index) => {

      if (
        userAnswers[index] ===
        question.correctAnswer
      ) {

        correctAnswers++;
      }
    }
  );

  const incorrectAnswers =
    questions.length -
    correctAnswers;

  const percentage =
    Math.round(
      (
        correctAnswers /
        questions.length
      ) * 100
    );


  // =========================================
  // GUARDAR RESULTADO
  // =========================================

    const result = {
    id: examId,
    exam: exam.title,
    subject: exam.subject,
    totalQuestions: questions.length,
    correctAnswers,
    incorrectAnswers,
    percentage,
    answers: userAnswers,

    questions: questions.map((question, index) => ({
        number: question.number,
        axis: question.axis,
        text: question.text,
        answers: question.answers,
        correctAnswer: question.correctAnswer,
        userAnswer: userAnswers[index] || null,
        correct:
        userAnswers[index] === question.correctAnswer
    }))
    };


  const storageKey = examType === "invierno"
    ? `paesWinterExamResult_${examId}`
    : `paesExamResult_${examId}`;

  localStorage.setItem(
    storageKey,
    JSON.stringify(result)
  );


  alert(
    `${exam.title} finalizado.\n\n` +
    `Correctas: ${correctAnswers}\n` +
    `Incorrectas: ${incorrectAnswers}\n` +
    `Resultado: ${percentage}%`
  );


  window.location.href = examType === "invierno"
    ? "asistencia.html?tipo=invierno"
    : "asistencia.html";
}


